const ALL = Object.values(LIST).flat();
const key = (b, r) => `${B[b][0]}|${r}`;
const MAKES = new Map(ALL.map(([k, b, r]) => [key(b, r), k]));

// 3組 えらぶ。部首も のこりも 同じ ものは 入れない。べつの組どうしで 漢字が できて しまう 組み合わせも さける
export function pickPairs(grade) {
  const pool = LIST[grade] || LIST[4];
  for (let t = 0; t < 300; t++) {
    const set = [];
    const used = new Set();
    while (set.length < 3) {
      const e = pool[Math.floor(rand() * pool.length)];
      if (set.includes(e)) continue;
      set.push(e);
    }
    const bs = set.map(e => B[e[1]][0]), rs = set.map(e => e[2]);
    if (new Set(bs).size < 3 || new Set(rs).size < 3) continue;
    if (bs.some(b => rs.includes(b))) continue;   // 部首と 同じ 字の のこりが あると まぎらわしい
    let cross = false;
    for (let i = 0; i < 3; i++) for (let j = 0; j < 3; j++) if (i !== j && MAKES.has(key(set[i][1], set[j][2]))) cross = true;
    if (cross) continue;
    used.clear();
    return set.map(([kanji, b, rest]) => ({ kanji, bushu: B[b][0], name: B[b][1], rest }));
  }
  return [LIST[4][0], LIST[4][11], LIST[4][18]].map(([kanji, b, rest]) => ({ kanji, bushu: B[b][0], name: B[b][1], rest }));
}

// 6まいの カード（まぜる）：{ pair: 組の番号, side: 'bushu' | 'rest' }
export function makeBoard(pairs) {
  const cards = [];
  pairs.forEach((_, i) => { cards.push({ pair: i, side: 'bushu' }, { pair: i, side: 'rest' }); });
  for (let i = cards.length - 1; i > 0; i--) { const j = Math.floor(rand() * (i + 1)); [cards[i], cards[j]] = [cards[j], cards[i]]; }
  return cards;
}

// CPU が めくる カード。seen＝見たことのある カード（番号→組）。つよさで 覚えている かくりつが かわる
export function cpuFlip(level, cards, taken, seen, first) {
  const mem = [0, 0.35, 0.65, 0.92][level] || 0.6;
  const open = cards.map((_, i) => i).filter(i => !taken[i] && i !== first);
  const remembered = open.filter(i => seen.has(i) && rand() < mem);
  if (first == null) {
    // 2まいとも 覚えている 組が あれば その1まい
    for (const i of remembered) if (remembered.some(j => j !== i && cards[j].pair === cards[i].pair)) return i;
    const fresh = open.filter(i => !seen.has(i));
    const list = fresh.length ? fresh : open;
    return list[Math.floor(rand() * list.length)];
  }
  const mate = remembered.find(i => cards[i].pair === cards[first].pair);
  if (mate != null) return mate;
  const fresh = open.filter(i => !seen.has(i));
  const list = fresh.length ? fresh : open;
  return list[Math.floor(rand() * list.length)];
}
